/**
 * Состояние долга как фильтр списка транзакций.
 *
 * Это не колонка в БД: значения выводятся из status + dueDate на момент
 * запроса. Отдельный фильтр нужен, чтобы рекомендации дашборда вели на
 * реальный отфильтрованный список, а не на «все транзакции».
 */
export enum DebtStatusFilter {
  /** Срок прошёл, долг не закрыт. */
  OVERDUE = 'OVERDUE',
  /** Срок наступает в ближайшие дни. */
  DUE_SOON = 'DUE_SOON',
  /** Любой незакрытый долг. */
  OUTSTANDING = 'OUTSTANDING',
  /** Долг закрыт полностью. */
  SETTLED = 'SETTLED',
}
